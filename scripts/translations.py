"""Sync, check and compile production translation artifacts and review digests."""

import argparse
import copy
import hashlib
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from io import BytesIO
from pathlib import Path
from tempfile import TemporaryDirectory

from babel.messages.catalog import Catalog
from babel.messages.mofile import write_mo
from babel.messages.pofile import normalize, read_po, write_po
from babel.support import Translations
from jinja2 import Environment, FileSystemLoader

ROOT = Path(__file__).resolve().parents[1]
TRANSLATIONS = ROOT / "translations"
LOCALES = ("de_CH", "fr_CH", "en", "it_CH")
NAMED_FORMAT = re.compile(r"%\([^)]+\)[#0 +.\-0-9]*[diouxXeEfFgGcrsa]")


def extract(destination):
    """Extract repository messages and normalize the generated POT deterministically."""
    _extract(destination, ROOT / "babel.cfg")
    with destination.open("rb") as handle:
        catalog = read_po(handle)
    catalog.creation_date = datetime(1970, 1, 1, tzinfo=UTC)
    catalog.header_comment = (
        "# OpenLEG source messages.\n# Generated by scripts/translations.py sync."
    )
    normalize_flags(catalog)
    with destination.open("wb") as handle:
        write_po(handle, catalog, width=100, sort_output=True)
    destination.write_bytes(destination.read_bytes().rstrip() + b"\n")
    return catalog


def _extract(destination, mapping):
    subprocess.run(
        [
            sys.executable,
            "-c",
            "from babel.messages.frontend import main; main()",
            "extract",
            "-F",
            str(mapping),
            "-k",
            "gettext_noop",
            "-k",
            "_l",
            "-k",
            "_N",
            "-k",
            "recipient_gettext",
            "-o",
            str(destination),
            ".",
        ],
        cwd=ROOT,
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
    )


def normalize_flags(catalog):
    """Keep named-format validation without misclassifying literal percent prose."""
    for message in catalog:
        identifiers = message.id if isinstance(message.id, tuple) else (message.id,)
        # Babel mistakes literal prose such as '40% ohne' for '% o'. Our
        # interpolation convention uses named placeholders exclusively.
        if not any(NAMED_FORMAT.search(text or "") for text in identifiers):
            message.flags.discard("python-format")


def validate(catalog, expected):
    """Require complete translations and matching placeholders for each source form.

    As in Babel, translation form zero corresponds to the singular msgid and
    every later form to the plural msgid, including languages with more than
    two forms. Keep the stricter rule that required named parameters cannot
    disappear. NAMED_FORMAT is a regex over repository text, not an XPath query.
    """
    actual = {(message.id, message.context) for message in catalog if message.id}
    missing = {
        (message.id, message.context) for message in expected if message.id
    } - actual
    problems = [
        f"Missing source message: {message}" for message in sorted(missing, key=str)
    ]
    extra = actual - {
        (message.id, message.context) for message in expected if message.id
    }
    problems.extend(
        f"Obsolete source message: {message}" for message in sorted(extra, key=str)
    )
    problems.extend(f"Obsolete PO entry: {key}" for key in catalog.obsolete)
    for message in catalog:
        if not message.id:
            continue
        values = (
            message.string if isinstance(message.string, tuple) else (message.string,)
        )
        if "fuzzy" in message.flags or not all(values):
            problems.append(f"Untranslated or fuzzy: {message.id}")
        identifiers = message.id if isinstance(message.id, tuple) else (message.id,)
        for index, value in enumerate(values):
            source = identifiers[min(index, len(identifiers) - 1)]
            source_parameters = set(NAMED_FORMAT.findall(source))
            if set(NAMED_FORMAT.findall(value or "")) != source_parameters:
                problems.append(f"Named placeholder mismatch: {message.id}: {value}")
    problems.extend(f"{message.id}: {errors}" for message, errors in catalog.check())
    if problems:
        raise ValueError("\n".join(problems))


def build_svg_assets(*, check):
    """Build code-native graphics from the same catalogs as the interface."""
    directory = ROOT / "templates/assets"
    sources = sorted(directory.rglob("*.svg"))
    if not sources:
        return
    environment = Environment(
        loader=FileSystemLoader(directory, encoding="utf-8"),
        autoescape=True,
        extensions=["jinja2.ext.i18n"],
        keep_trailing_newline=True,
    )
    for path in sorted(TRANSLATIONS.glob("*/LC_MESSAGES/messages.mo")):
        locale = path.parent.parent.name
        environment.install_gettext_translations(
            Translations.load(TRANSLATIONS, locales=[locale]),
            newstyle=False,
        )
        for source in sources:
            relative = source.relative_to(directory)
            rendered = environment.get_template(relative.as_posix()).render()
            ET.fromstring(rendered)
            destination = ROOT / "static/images" / relative
            if locale != "de_CH":
                destination = (
                    destination.parent / locale.replace("_", "-") / destination.name
                )
            if check:
                if (
                    not destination.exists()
                    or destination.read_text(encoding="utf-8") != rendered
                ):
                    raise ValueError(f"Localized asset is stale: {destination}")
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(rendered, encoding="utf-8")


def load(path, locale=None):
    with path.open("rb") as handle:
        return read_po(handle, locale=locale, abort_invalid=True)


def entry_text(message, locale):
    """Serialize a new entry at fixed width, without rewriting existing catalogs."""
    lines = ["#. " + comment for comment in message.auto_comments]
    lines += ["# " + comment for comment in message.user_comments]
    if message.locations:
        lines += [
            "#: " + " ".join(f"{file}:{line}" for file, line in message.locations)
        ]
    if message.flags:
        lines += ["#, " + ", ".join(sorted(message.flags))]
    if message.context is not None:
        lines += ["msgctxt " + normalize(message.context, width=100)]
    if isinstance(message.id, tuple):
        lines += [
            "msgid " + normalize(message.id[0], width=100),
            "msgid_plural " + normalize(message.id[1], width=100),
        ]
        values = message.string or ("",) * Catalog(locale=locale).num_plurals
        lines += [
            f"msgstr[{index}] " + normalize(value, width=100)
            for index, value in enumerate(values)
        ]
    else:
        lines += [
            "msgid " + normalize(message.id, width=100),
            "msgstr " + normalize(message.string or "", width=100),
        ]
    return "\n".join(lines)


def merge(path, expected, locale):
    """Keep surviving PO blocks verbatim; prune obsolete blocks and append new ones.

    Exact identity includes context and plural source. Fuzzy matching would silently
    attach an old translation to different source text, so it is deliberately absent.
    """
    if path.exists():
        blocks = re.split(r"\n\s*\n", path.read_text(encoding="utf-8").strip())
        header = blocks[0]
    else:
        catalog = Catalog(locale=locale, project="OpenLEG")
        catalog.creation_date = datetime(1970, 1, 1, tzinfo=UTC)
        output = BytesIO()
        write_po(output, catalog, width=100)
        header = output.getvalue().decode("utf-8").strip()
        blocks = [header]
    wanted = {
        (message.id, message.context): message for message in expected if message.id
    }
    retained = [header]
    seen = set()
    for block in blocks[1:]:
        parsed = read_po(
            BytesIO((header + "\n\n" + block + "\n").encode("utf-8")),
            locale=locale,
            abort_invalid=True,
        )
        for message in parsed:
            key = (message.id, message.context)
            if not message.id or key not in wanted:
                continue
            if key in seen:
                raise ValueError(f"Duplicate PO entry: {path}: {key}")
            seen.add(key)
            retained.append(block)
    for key, source in wanted.items():
        if key in seen:
            continue
        message = copy.deepcopy(source)
        message.string = (
            message.id
            if locale == "de_CH"
            else (
                ("",) * Catalog(locale=locale).num_plurals
                if isinstance(message.id, tuple)
                else ""
            )
        )
        message.flags.discard("fuzzy")
        if locale != "de_CH":
            message.auto_comments.append(
                "Draft translation; native language and domain review pending."
            )
        retained.append(entry_text(message, locale))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(retained) + "\n", encoding="utf-8")


def semantic(catalog):
    """Digest semantic text and contexts, excluding generated metadata and locations."""
    items = [
        {"id": message.id, "context": message.context, "string": message.string}
        for message in catalog
        if message.id
    ]
    items.sort(
        key=lambda item: (
            json.dumps(item["id"], ensure_ascii=False),
            item["context"] or "",
        )
    )
    return len(items), hashlib.sha256(
        json.dumps(items, ensure_ascii=False, sort_keys=True).encode("utf-8")
    ).hexdigest()


def review_state(expected, catalogs, *, check):
    path = TRANSLATIONS / "review-status.json"
    state = (
        json.loads(path.read_text(encoding="utf-8"))
        if path.exists()
        else {
            "schema": "openleg-translation-review/1",
            "status": "draft",
            "native_approval": False,
            "legal_approval": False,
            "locales": {},
        }
    )
    before = copy.deepcopy(state)
    count, digest = semantic(expected)
    source_changed = state.get("source_digest") != digest
    changed = [
        locale
        for locale, catalog in catalogs.items()
        if source_changed
        or state["locales"].get(locale, {}).get("catalog_digest")
        != semantic(catalog)[1]
    ]
    if check:
        if source_changed or state.get("source_messages") != count or changed:
            raise ValueError(
                f"Stale review digests: source={source_changed}, locales={changed}; run sync"
            )
        return
    if changed:
        # Keep evidence attached to its old digests instead of relabelling it as
        # review of the new text. No timestamp is generated during repeat syncs.
        reviewed = {
            locale: copy.deepcopy(state["locales"][locale])
            for locale in changed
            if locale in state["locales"]
            and (
                state["locales"][locale].get("native_review_status", "pending")
                != "pending"
                or any(
                    state["locales"][locale].get(key)
                    for key in ("reviewer", "reviewed_at", "evidence_reference")
                )
            )
        }
        if reviewed or state.get("native_approval") or state.get("legal_approval"):
            state.setdefault("superseded_reviews", []).append(
                {
                    "source_digest": state.get("source_digest"),
                    "locales": reviewed,
                    "native_approval": state.get("native_approval", False),
                    "legal_approval": state.get("legal_approval", False),
                }
            )
        state.update(status="draft", native_approval=False, legal_approval=False)
    state.update(source_messages=count, source_digest=digest)
    for locale, catalog in catalogs.items():
        entry = state["locales"].setdefault(locale, {})
        if locale in changed:
            entry.update(
                native_review_status="pending",
                reviewer=None,
                reviewed_at=None,
                evidence_reference=None,
            )
        entry["catalog_digest"] = semantic(catalog)[1]
    if state != before or not path.exists():
        path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")


def compiled_bytes(catalog):
    result = BytesIO()
    write_mo(result, catalog)
    return result.getvalue()


def run(command):
    if command == "extract":
        TRANSLATIONS.mkdir(parents=True, exist_ok=True)
        catalog = extract(TRANSLATIONS / "messages.pot")
        print(f"Extracted {len(catalog)} source messages")
        return
    with TemporaryDirectory(prefix="openleg-i18n-") as directory:
        temporary = Path(directory) / "messages.pot"
        expected = extract(temporary)
        pot = temporary.read_bytes()
    source_path = TRANSLATIONS / "messages.pot"
    if command == "check" and (
        not source_path.exists() or source_path.read_bytes() != pot
    ):
        raise ValueError("Source/POT drift: translations/messages.pot; run sync")
    if command == "sync":
        TRANSLATIONS.mkdir(parents=True, exist_ok=True)
        source_path.write_bytes(pot)
    catalogs = {}
    for locale in LOCALES:
        path = TRANSLATIONS / locale / "LC_MESSAGES/messages.po"
        if command == "sync":
            merge(path, expected, locale)
        if not path.exists():
            raise ValueError(
                f"Missing catalog: {path}; run sync and author translations"
            )
        catalogs[locale] = load(path, locale)
        normalize_flags(catalogs[locale])
    if command == "sync":
        review_state(expected, catalogs, check=False)
    # Validate all inputs before replacing any compiled output.
    for locale, catalog in catalogs.items():
        try:
            validate(catalog, expected)
        except ValueError as error:
            raise ValueError(
                f"translations/{locale}/LC_MESSAGES/messages.po: {error}\n"
                "Author missing translations and resolve fuzzy entries explicitly; then run sync."
            ) from error
    for locale, catalog in catalogs.items():
        target = TRANSLATIONS / locale / "LC_MESSAGES/messages.mo"
        data = compiled_bytes(catalog)
        if command == "check":
            if not target.exists() or target.read_bytes() != data:
                raise ValueError(
                    f"Compiled catalog or plural rules are stale: {target}; run sync"
                )
        else:
            target.write_bytes(data)
        print(
            f"{target.with_suffix('.po').relative_to(ROOT)}: {len(catalog)} translated messages, OK"
        )
    build_svg_assets(check=command == "check")
    if command == "check":
        review_state(expected, catalogs, check=True)
    print(
        "Translation artifacts, localized SVGs and review digests: OK"
        if command != "compile"
        else "Compiled catalogs and localized SVGs: OK"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("extract", "sync", "check", "compile"))
    args = parser.parse_args()
    run(args.command)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        sys.exit(str(error))
