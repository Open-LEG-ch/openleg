"""Regenerate swiss_postcodes.py from the official building address directory.

Download the CSV (LV95) of "Amtliches Gebäudeadressverzeichnis" from
https://data.geo.admin.ch/ch.swisstopo.amtliches-gebaeudeadressverzeichnis/amtliches-gebaeudeadressverzeichnis_ch/amtliches-gebaeudeadressverzeichnis_ch_2056.csv.zip
Then run, with the data state shown on the download page:

    python scripts/update_swiss_postcodes.py amtliches-gebaeudeadressverzeichnis_ch_2056.csv.zip 2026-11-26

It counts the existing addresses of every postcode per municipality and
locality. Planned addresses are left out.
"""

import csv
import io
import re
import sys
import zipfile
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "swiss_postcodes.py"
# A postcode finds a municipality that holds at least one percent of its
# addresses, and always the one that holds the most. A locality name is listed
# for a municipality that holds at least ten percent of that locality.
MIN_POSTCODE_SHARE = 1
MIN_LOCALITY_SHARE = 10

HEADER = '''# SPDX-License-Identifier: AGPL-3.0-or-later
"""Swiss postcodes and localities per BFS municipality.

Source: swisstopo, Amtliches Gebäudeadressverzeichnis
(ch.swisstopo.amtliches-gebaeudeadressverzeichnis). Open government data, free
use with attribution. Generated by scripts/update_swiss_postcodes.py; do not
edit by hand. One line per municipality and postcode: BFS number;postcode;
existing addresses of the postcode in the municipality;localities.
"""

from functools import cache

SOURCE = "swisstopo, Amtliches Gebäudeadressverzeichnis"
STATE = "{state}"

_DATA = """\\
{data}"""


@cache
def postcodes_by_municipality():
    """Return {{bfs_number: ((postcode, share_pct, localities), ...)}}.

    The share is the municipality's part of the postcode's addresses among
    the municipalities listed for that postcode, unrounded.
    """
    rows = [line.split(";") for line in _DATA.splitlines()]
    totals = {{}}
    for _bfs, postcode, addresses, _localities in rows:
        totals[postcode] = totals.get(postcode, 0) + int(addresses)
    result = {{}}
    for bfs, postcode, addresses, localities in rows:
        result.setdefault(int(bfs), []).append(
            (
                postcode,
                100 * int(addresses) / totals[postcode],
                tuple(filter(None, localities.split("|"))),
            )
        )
    return {{bfs: tuple(entries) for bfs, entries in result.items()}}
'''


def _increment(counts, key):
    counts[key] = counts.get(key, 0) + 1


def build(rows):
    """One line per municipality and postcode with its existing addresses."""
    per_postcode = {}
    per_municipality = {}
    per_locality = {}
    per_locality_municipality = {}
    for row in rows:
        if row["ADR_STATUS"] != "real":
            continue
        postcode, _space, locality = row["ZIP_LABEL"].strip().partition(" ")
        bfs = int(row["COM_FOSNR"])
        _increment(per_postcode, postcode)
        _increment(per_municipality, (bfs, postcode))
        _increment(per_locality, (postcode, locality))
        _increment(per_locality_municipality, (bfs, postcode, locality))
    shares = {
        key: 100 * count / per_postcode[key[1]]
        for key, count in per_municipality.items()
    }
    best = {}
    for (_bfs, postcode), share in shares.items():
        best[postcode] = max(best.get(postcode, 0.0), share)
    names = {}
    for (bfs, postcode, locality), count in per_locality_municipality.items():
        if 100 * count / per_locality[(postcode, locality)] >= MIN_LOCALITY_SHARE:
            names.setdefault((bfs, postcode), set()).add(locality)
    lines = []
    for (bfs, postcode), share in sorted(shares.items()):
        if share < MIN_POSTCODE_SHARE and share < best[postcode]:
            continue
        place = "|".join(sorted(names.get((bfs, postcode), ())))
        addresses = per_municipality[(bfs, postcode)]
        lines.append(f"{bfs};{postcode};{addresses};{place}")
    return "\n".join(lines) + "\n"


def _rows(path):
    if path.endswith(".zip"):
        with zipfile.ZipFile(path) as archive:
            (name,) = [name for name in archive.namelist() if name.endswith(".csv")]
            with archive.open(name) as raw:
                text = io.TextIOWrapper(raw, encoding="utf-8-sig", newline="")
                yield from csv.DictReader(text, delimiter=";")
    else:
        with open(path, encoding="utf-8-sig", newline="") as handle:
            yield from csv.DictReader(handle, delimiter=";")


def main(argv):
    if len(argv) != 3 or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", argv[2]):
        print(__doc__)
        return 2
    data = build(_rows(argv[1]))
    TARGET.write_text(HEADER.format(state=argv[2], data=data), encoding="utf-8")
    print(f"{TARGET.name}: {data.count(chr(10))} postcode entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
