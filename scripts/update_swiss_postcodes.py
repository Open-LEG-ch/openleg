"""Regenerate swiss_postcodes.py from the official swisstopo locality list.

Download the CSV (LV95) of "Amtliches Ortschaftenverzeichnis mit Postleitzahl
und Perimeter" from
https://data.geo.admin.ch/ch.swisstopo-vd.ortschaftenverzeichnis_plz/ortschaftenverzeichnis_plz/ortschaftenverzeichnis_plz_2056.csv.zip
and unpack it. Then run:

    python scripts/update_swiss_postcodes.py AMTOVZ_CSV_LV95.csv 2026-11-01

The second argument is the data state shown on the download page.
"""

import csv
import re
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "swiss_postcodes.py"
# A postcode whose addresses mostly lie elsewhere still finds this municipality,
# but only from a one percent share on. A locality name needs ten percent of
# that locality's addresses.
MIN_POSTCODE_SHARE = 1
MIN_LOCALITY_SHARE = 10

HEADER = '''# SPDX-License-Identifier: AGPL-3.0-or-later
"""Swiss postcodes and localities per BFS municipality.

Source: swisstopo, Amtliches Ortschaftenverzeichnis mit Postleitzahl und
Perimeter (ch.swisstopo-vd.ortschaftenverzeichnis_plz). Open government data,
free use with attribution. Generated by scripts/update_swiss_postcodes.py;
do not edit by hand. One line per municipality and postcode:
BFS number;postcode;share of the postcode's addresses in percent;localities.
"""

from functools import cache

SOURCE = "swisstopo, Amtliches Ortschaftenverzeichnis"
STATE = "{state}"

_DATA = """\\
{data}"""


@cache
def postcodes_by_municipality():
    """Return {{bfs_number: ((postcode, share_pct, localities), ...)}}."""
    result = {{}}
    for line in _DATA.splitlines():
        bfs, postcode, share, localities = line.split(";")
        result.setdefault(int(bfs), []).append(
            (postcode, int(share), tuple(filter(None, localities.split("|"))))
        )
    return {{bfs: tuple(entries) for bfs, entries in result.items()}}
'''


def build(rows):
    """One line per municipality and postcode with its share of the postcode.

    The directory gives each municipality's share of the addresses of one
    locality (ZIP_ID), not address counts. Each locality of a postcode
    therefore weighs the same.
    """
    localities = {}
    shares = {}
    names = {}
    for row in rows:
        bfs = int(row["BFS-Nr"])
        postcode = row["PLZ4"].strip()
        share = float(row["Adressenanteil"].replace("%", "").strip())
        name = re.sub(r"\s+\d+$", "", row["Ortschaftsname"]).strip()
        localities.setdefault(postcode, set()).add(row["ZIP_ID"])
        key = (bfs, postcode)
        shares[key] = shares.get(key, 0.0) + share
        if share >= MIN_LOCALITY_SHARE:
            names.setdefault(key, set()).add(name)
    shares = {
        (bfs, postcode): total / len(localities[postcode])
        for (bfs, postcode), total in shares.items()
    }
    best = {}
    for (bfs, postcode), share in shares.items():
        best[postcode] = max(best.get(postcode, 0.0), share)
    lines = []
    for (bfs, postcode), share in sorted(shares.items()):
        if share < MIN_POSTCODE_SHARE and share < best[postcode]:
            continue
        place = "|".join(sorted(names.get((bfs, postcode), ())))
        lines.append(f"{bfs};{postcode};{max(1, round(share))};{place}")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3 or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", argv[2]):
        print(__doc__)
        return 2
    with open(argv[1], encoding="utf-8-sig", newline="") as handle:
        data = build(csv.DictReader(handle, delimiter=";"))
    TARGET.write_text(HEADER.format(state=argv[2], data=data), encoding="utf-8")
    print(f"{TARGET.name}: {data.count(chr(10))} postcode entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
